export const GLYPH_H = 7;

export function glyphRows(ch) {
  return RAW[ch.toUpperCase()] ?? null;
}

/**
 * Lay a string out as lit cells.
 * `gap` is the blank columns between glyphs, `colonGap` the gap on either side of a colon,
 * `spaceW` the width of a space. Returns cell coordinates in a width x 7 grid.
 */
export function layoutText(str, { gap = 1, colonGap = 2, spaceW = 3 } = {}) {
  const cells = [];
  const glyphs = [];
  let x = 0;
  let prev = null;
  for (const raw of str) {
    if (raw === ' ') {
      x += spaceW;
      prev = ' ';
      continue;
    }
    const ch = raw.toUpperCase();
    const rows = RAW[ch];
    if (!rows) continue;
    if (prev !== null && prev !== ' ') x += ch === ':' || prev === ':' ? colonGap : gap;
    const w = rows[0].length;
    for (let y = 0; y < GLYPH_H; y++) {
      for (let cx = 0; cx < w; cx++) if (rows[y][cx] === '#') cells.push([x + cx, y]);
    }
    glyphs.push({ ch, x, w });
    x += w;
    prev = ch;
  }
  return { width: x, height: GLYPH_H, cells, glyphs };
}
